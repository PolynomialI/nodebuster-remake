// Copies the assets the remake uses from reference/extracted/ into assets-gen/
// (gitignored) and writes assets-gen/assets.ts, which imports each one with
// Vite's ?inline so the build embeds them in index.html. Music and the long
// ending noise go to assets-gen/public/ and are streamed after start.
//
// Audio is re-encoded to Opus (Ogg container) with ffmpeg from .tools/ffmpeg
// or PATH. Encoded files are cached by source mtime.
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'reference', 'extracted');
const out = join(root, 'assets-gen');
const content = (f) => JSON.parse(readFileSync(join(root, 'content', f), 'utf8'));

if (!existsSync(src)) {
  console.error('reference/extracted/ is missing. Recover the game first (see research/README.md).');
  process.exit(1);
}

const manifest = content('assets.json');
const localFfmpeg = join(root, '.tools', 'ffmpeg', 'bin', process.platform === 'win32' ? 'ffmpeg.exe' : 'ffmpeg');
const ffmpeg = existsSync(localFfmpeg) ? localFfmpeg : 'ffmpeg';

// Icons referenced by content (e.g. "upgrade/Damage1") resolve through iconDirs.
const images = { ...manifest.images };
for (const [file, key] of [['upgrades.json', 'nodes'], ['milestones.json', 'milestones']]) {
  if (!existsSync(join(root, 'content', file))) continue;
  for (const item of content(file)[key] ?? []) {
    if (!item.icon) continue;
    const slash = item.icon.indexOf('/');
    const dir = manifest.iconDirs[item.icon.slice(0, slash + 1)];
    if (!dir) throw new Error(`${file}: no iconDirs entry for ${item.icon}`);
    images[item.icon] = dir + item.icon.slice(slash + 1) + '.png';
  }
}

const safe = (id) => id.replace(/[^A-Za-z0-9_.-]/g, '__');
const ensure = (p) => mkdirSync(dirname(p), { recursive: true });
const newer = (a, b) => existsSync(b) && statSync(b).mtimeMs >= statSync(a).mtimeMs;

function encode(input, output, bitrate) {
  ensure(output);
  if (newer(input, output)) return;
  execFileSync(ffmpeg, ['-y', '-loglevel', 'error', '-i', input, '-map_metadata', '-1', '-c:a', 'libopus', '-b:a', bitrate, '-vbr', 'on', '-application', 'audio', output], { stdio: 'inherit' });
}

const lines = ['// Generated by scripts/build-assets.mjs. Do not edit or commit.'];
const imgEntries = [];
const sfxEntries = [];
const fontEntries = [];
let n = 0;

for (const [id, rel] of Object.entries(images)) {
  const from = join(src, rel);
  if (!existsSync(from)) throw new Error(`Missing image for ${id}: ${rel}`);
  const to = join(out, 'img', `${safe(id)}.png`);
  ensure(to);
  copyFileSync(from, to);
  const v = `a${n++}`;
  lines.push(`import ${v} from './img/${safe(id)}.png?inline';`);
  imgEntries.push(`  ${JSON.stringify(id)}: ${v},`);
}

for (const [id, rel] of Object.entries(manifest.fonts)) {
  const to = join(out, 'font', `${safe(id)}.ttf`);
  ensure(to);
  copyFileSync(join(src, rel), to);
  const v = `a${n++}`;
  lines.push(`import ${v} from './font/${safe(id)}.ttf?inline';`);
  fontEntries.push(`  ${JSON.stringify(id)}: ${v},`);
}

for (const [id, files] of Object.entries(manifest.sfx)) {
  const vars = [];
  files.forEach((rel, i) => {
    const to = join(out, 'sfx', `${safe(id)}_${i}.ogg`);
    encode(join(src, rel), to, manifest.encoding.sfx.bitrate);
    const v = `a${n++}`;
    lines.push(`import ${v} from './sfx/${safe(id)}_${i}.ogg?inline';`);
    vars.push(v);
  });
  sfxEntries.push(`  ${JSON.stringify(id)}: [${vars.join(', ')}],`);
}

const streamed = {};
for (const [id, rel] of Object.entries(manifest.streamed)) {
  const name = `sfx/${safe(id)}.ogg`;
  encode(join(src, rel), join(out, 'public', name), manifest.encoding.streamed.bitrate);
  streamed[id] = name;
}
const music = manifest.music.map((rel, i) => {
  const name = `music/track${String(i + 1).padStart(2, '0')}.ogg`;
  encode(join(src, rel), join(out, 'public', name), manifest.encoding.streamed.bitrate);
  return name;
});

lines.push('', 'export const images: Record<string, string> = {', ...imgEntries, '};');
lines.push('export const fonts: Record<string, string> = {', ...fontEntries, '};');
lines.push('export const sfx: Record<string, string[]> = {', ...sfxEntries, '};');
lines.push(`export const streamed: Record<string, string> = ${JSON.stringify(streamed)};`);
lines.push(`export const music: string[] = ${JSON.stringify(music)};`, '');
writeFileSync(join(out, 'assets.ts'), lines.join('\n'));

console.log(`assets-gen: ${imgEntries.length} images, ${fontEntries.length} fonts, ${sfxEntries.length} sfx, ${music.length} music tracks`);
